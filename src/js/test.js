export function addProduct(newProducts) {
  let products = JSON.parse(localStorage.getItem("products")) || [];

  // Duyệt qua mảng sản phẩm mới để thêm vào
  newProducts.forEach((newItem) => {
    const existingIndex = products.findIndex((p) => p.id === newItem.id);
    if (existingIndex !== -1) {
      products[existingIndex] = newItem; // Nếu trùng ID thì cập nhật mới
    } else {
      products.push(newItem); // Nếu chưa có thì thêm vào cuối
    }
  });

  localStorage.setItem("products", JSON.stringify(products));
}

